"""The input area pinned to the bottom of the terminal window during an interactive conversation.

The terminal's scroll region keeps everything the program prints (answers, command rows, consent questions) above a
fixed block of RESERVED rows: an empty spacer, a three-row input band, a status line and a key hint. Every byte written here is
generated by this module; the user's text reaches it already validated by the editor. Colour terminals only; anything
else keeps the ordinary inline prompt.
"""
import os
import re
import signal
import sys
import threading
import time

from .terminal_style import bar, enabled, paint

RESERVED = 6               # spacer, band top padding, input row, band bottom padding, status, hint
MIN_ROWS = 12
PLACEHOLDER = "Ask ai-desktop to do anything"
POPUP_ROWS = 8             # `/` commands listed above the band at once
_PICKED = ((88, 140, 230), "44")
HINT = "enter send · \\ enter new line · / commands · ctrl+c clear"

_current = None
HISTORY_HINT = "history · PgUp/PgDn or the wheel to move · End or any key: back to the conversation"
_ENTER_FULL, _LEAVE_FULL = "\x1b[?1049h\x1b[H\x1b[2J", "\x1b[?1049l"
# Button-event tracking: presses, releases, drags with a button held and the wheel, reported in SGR form.
_MOUSE_ON, _MOUSE_OFF = "\x1b[?1002h\x1b[?1006h", "\x1b[?1002l\x1b[?1000l\x1b[?1006l"
_REPORT = re.compile(r"\[<(\d{1,3});(\d{1,5});(\d{1,5})([Mm])")
DOUBLE_CLICK = 0.4
WL_COPY = "/usr/bin/wl-copy"


def copy_to_clipboard(text, stream, *, environ=None):
    """The selected text to the clipboard: OSC 52 through the terminal (and a multiplexer such as Zellij or tmux that
    passes it on), and wl-copy on Wayland when it is installed. Only the owner's own screen text is copied."""
    import base64
    import subprocess
    data = text.encode("utf-8")
    if not data or len(data) > 1024 * 1024:
        return False
    stream.write("\x1b]52;c;" + base64.b64encode(data).decode("ascii") + "\x07")
    stream.flush()
    environ = os.environ if environ is None else environ
    if environ.get("WAYLAND_DISPLAY") and os.path.isfile(WL_COPY) and os.access(WL_COPY, os.X_OK):
        try:
            process = subprocess.Popen([WL_COPY], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                                       stderr=subprocess.DEVNULL, close_fds=True, start_new_session=True)
            process.stdin.write(data)
            process.stdin.close()
        except OSError:
            pass
    return True


class Screen:
    """sys.stdout in the full-screen view: every write reaches the terminal and the screen model (see screen_model).
    While earlier rows are shown, writes only update the model; going back draws the live screen again from it."""

    def __init__(self, stream, rows, columns):
        from .screen_model import ScreenModel
        self._stream = stream
        self.model = ScreenModel(rows, columns)
        self.offset = 0
        self.lock = threading.RLock()

    selecting = False

    def write(self, text):
        with self.lock:
            self.model.feed(text)
            if not self.offset and not self.selecting:
                self._stream.write(text)
            return len(text)

    def highlight(self, top_rows, first, last):
        """Draw the conversation area at the current offset with the cells between two absolute points reversed."""
        from .screen_model import ScreenModel
        with self.lock:
            start, rows = self.model.window(top_rows, self.offset)
            (row_a, col_a), (row_b, col_b) = sorted((first, last))
            out = []
            for index, cells in enumerate(rows):
                absolute = start + index
                line = list(cells)
                if row_a <= absolute <= row_b:
                    left = col_a if absolute == row_a else 0
                    right = col_b if absolute == row_b else len(line) - 1
                    for column in range(max(0, left), min(len(line) - 1, right) + 1):
                        char, style = line[column]
                        line[column] = (char, style + "\x1b[7m")
                out.append("\x1b[%d;1H\x1b[0m\x1b[2K%s" % (index + 1, ScreenModel.render(line)))
            self._stream.write("".join(out) + "\x1b[%d;%dH" % (self.model.row + 1, self.model.column + 1))
            self._stream.flush()

    def unfreeze(self, top_rows, note=None, columns=80):
        """End a selection: the view as it was (live or history), then a short note on the bottom row."""
        with self.lock:
            self.selecting = False
            if self.offset:
                self._stream.write(self.model.view(top_rows, self.offset))
            else:
                self._stream.write(self.model.repaint(region=False))
            if note:
                self._stream.write("\x1b[%d;1H\x1b[0m\x1b[2K%s\x1b[%d;%dH" % (
                    self.model.rows, paint(note[:max(1, columns - 1)], "accent", stream=self._stream),
                    self.model.row + 1, self.model.column + 1))
            self._stream.flush()

    def raw(self, text):
        """Control sequences for the terminal only (screen mode, mouse): not part of what the model shows."""
        with self.lock:
            self._stream.write(text)
            self._stream.flush()

    def flush(self):
        with self.lock:
            self._stream.flush()

    def show(self, offset, top_rows, columns):
        """Show the conversation `offset` rows back (0 = live) in the first `top_rows` rows; the rows below stay."""
        with self.lock:
            offset = max(0, min(offset, len(self.model.history)))
            if offset == self.offset:
                return
            self.offset = offset
            if offset:
                note = paint(HISTORY_HINT[:max(1, columns - 1)], "accent", stream=self._stream)
                self._stream.write(self.model.view(top_rows, offset) + "\x1b[%d;1H\x1b[0m\x1b[2K%s" % (
                    self.model.rows, note) + "\x1b[%d;%dH" % (self.model.row + 1, self.model.column + 1))
            else:
                self._stream.write(self.model.repaint(region=False))
            self._stream.flush()

    def resize(self, rows, columns, old_top, new_top):
        with self.lock:
            self.model.refit(rows, columns, old_top, new_top)
            self.offset = 0
            self._stream.write("\x1b[r\x1b[H\x1b[2J" + self.model.repaint(saved=True))
            self._stream.flush()

    def __getattr__(self, name):
        return getattr(self._stream, name)


def view_setting(home=None):
    """The chosen conversation view: "fullscreen" (the default) or "inline", from ~/.config/ai-desktop/view."""
    from pathlib import Path
    try:
        path = Path(home or os.path.expanduser("~")) / ".config" / "ai-desktop" / "view"
        descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        try:
            value = os.read(descriptor, 64).decode("ascii").strip()
        finally:
            os.close(descriptor)
        return value if value in ("fullscreen", "inline") else "fullscreen"
    except (OSError, ValueError):
        return "fullscreen"


def _call(frame, name, *args):
    """A full-screen method of a frame that has it (a stand-in in tests may not)."""
    method = getattr(frame, name, None)
    if callable(method):
        method(*args)


def current():
    """The active frame, or None (then the editor draws inline as before)."""
    return _current


def _size(stream):
    try:
        size = os.get_terminal_size(stream.fileno())
        return size.lines, size.columns
    except (OSError, ValueError, AttributeError):
        return 0, 0


class Frame:
    def __init__(self, stream, status, *, fullscreen=False):
        self.screen = None
        self._plain = stream                       # the terminal itself (sys.stdout before the full-screen view)
        if fullscreen:
            rows, columns = _size(stream)
            self.screen = Screen(stream, rows, columns)
            stream = self.screen
        self.stream = stream
        self.status = status
        self.rows, self.columns = _size(stream)
        self.note = ""
        self._resized = False
        self._moved = False                        # the window changed size since the conversation position was saved
        self.editing = None                        # (text, cursor) while the editor waits for keys
        self.repaint = None                        # prints the head and the thread again after a resize
        self.commands, self.pick = (), 0           # the `/` list shown above the band, and its highlighted row
        self.extra = 0                             # rows above the default reserved block: the `/` list and extra input rows
        self.listed = 0                            # rows of the `/` list right now
        self.lines = 1                             # rows of the input band's text right now
        self.cursor_at = (1, 1)                    # where the input cursor was last drawn
        self.busy = None                           # the live input of a running turn, which redraws itself
        self.draft = ""                            # text typed during a turn, put back into the next prompt
        self._previous_handler = None
        self._mouse = False
        self._mark = 0                              # rows already on the ordinary screen before the full-screen view

    # -- region ------------------------------------------------------------------------------------------------------
    def _top(self):
        """The last row of the conversation's scroll region."""
        return self.rows - RESERVED - self.extra

    def _reserve(self, listed, lines):
        """Room above the band for the `/` list and for input text longer than one row. The conversation scrolls up to
        make room (nothing is covered) and the region shrinks; when they shrink, the region grows back and the freed
        rows are cleared. The conversation always keeps at least three rows; the input takes at most about half."""
        room = max(0, self.rows - RESERVED - 3)
        self.lines = max(1, min(lines, room // 2 + 1))
        self.listed = max(0, min(listed, POPUP_ROWS, room - (self.lines - 1)))
        self._list_rows(self.listed + self.lines - 1)

    def _list_rows(self, wanted):
        wanted = max(0, wanted)
        delta = wanted - self.extra
        if not delta:
            return
        old = self._top()
        if delta > 0 and self.screen is not None:
            # Full-screen view: the conversation moves up only as far as its end must, to stay above the list; with
            # room below it nothing moves (no copies of the waiting line, no gaps; CachyOS check of candidate 154).
            end = self.screen.model.saved[0] + 1               # 1-based row of the conversation's end
            need = max(0, end - (old - delta))
            if need:
                self.stream.write("\x1b[%d;1H" % old + "\n" * need)
            self.extra = wanted
            self.stream.write("\x1b[1;%dr" % self._top())
            if need:
                self.stream.write("\x1b8\x1b[%dA\x1b7" % need)
        elif delta > 0:
            self.stream.write("\x1b[%d;1H" % old + "\n" * delta)
            self.extra = wanted
            self.stream.write("\x1b[1;%dr" % self._top())
            if not self._moved:
                self.stream.write("\x1b8\x1b[%dA\x1b7" % delta)    # the end of the conversation moved up with it
        else:
            self.extra = wanted
            self.stream.write("\x1b[1;%dr" % self._top()
                              + "".join("\x1b[%d;1H\x1b[2K" % row for row in range(old + 1, self._top() + 1)))

    def _region(self):
        """Keep the cursor above the reserved rows and limit scrolling to the area above them."""
        top = self.rows - RESERVED
        # Make room first: newlines scroll old content up when the cursor is low, then the cursor goes back up.
        self.stream.write("\n" * RESERVED + "\x1b[%dA" % RESERVED + "\x1b7" + "\x1b[1;%dr" % top + "\x1b8")

    def start(self):
        if self.screen is not None:
            self.screen.raw(_ENTER_FULL)
            sys.stdout = self.screen               # every print goes through the screen model
        self._region()
        try:
            self._previous_handler = signal.signal(signal.SIGWINCH, self._on_resize)
        except (ValueError, OSError):              # not the main thread: resizing is then handled on the next draw
            self._previous_handler = None
        self.draw("", 0, typing=False)
        self.editing = None
        self.stream.write("\x1b8")                 # back to the conversation, above the reserved rows
        self.stream.flush()

    def _on_resize(self, *unused):
        """Redraw at once while the editor waits for a key, so the band follows the window; otherwise on the next draw."""
        self._resized = True
        if self.busy is not None:                  # during a turn: only the band, never a full redraw
            try:
                self.busy.draw()
            except (OSError, ValueError):
                pass
            return
        if self.editing is not None:
            try:
                self.draw(*self.editing)
            except (OSError, ValueError):
                pass

    def _refresh_size(self, typing=False):
        rows, columns = _size(self.stream)
        if rows < MIN_ROWS or columns < 20:
            rows, columns = self.rows, self.columns         # an unreadable or tiny size: keep the last good one
        if (rows, columns) != (self.rows, self.columns) or self._resized:
            self._resized = False
            old = self._top()
            if self.screen is not None and (rows, columns) != (self.rows, self.columns):
                # The model keeps the whole conversation: it is laid out again so that its end stays right above the
                # input (no gap, nothing printed twice), and the next text continues there.
                self.rows, self.columns = rows, columns
                self.screen.resize(rows, columns, old, self._top())
                self.stream.write("\x1b[1;%dr" % self._top())
                self._moved = False
                return
            self.rows, self.columns = rows, columns
            if typing and self.repaint is not None:
                # A terminal that grows pulls old lines back in at the top and shifts everything down. Like Codex, draw
                # the conversation again instead: clear the window, set the region, print the head and the thread.
                top = self._top()
                self.stream.write("\x1b[r\x1b[H\x1b[2J\x1b[1;%dr\x1b[H" % top)
                self.stream.flush()
                try:
                    self.repaint()
                except (OSError, ValueError, TypeError, KeyError):
                    pass
                self.stream.write("\x1b7")
                self._moved = False
                return
            # The old reserved rows may now sit inside the conversation: clear from whichever reserved block starts
            # higher, then set the region again. No save/restore here: that slot holds the conversation position.
            top = self._top()
            self.stream.write("\x1b[r\x1b[%d;1H\x1b[J\x1b[1;%dr" % (max(1, min(old, top) + 1), top))
            self._moved = True

    def _back(self):
        """To the conversation text: the saved position, or the last region row when the window size changed."""
        if self._moved:
            self._moved = False
            return "\x1b[%d;1H" % self._top()
        return "\x1b8"

    # -- drawing -----------------------------------------------------------------------------------------------------
    @staticmethod
    def wrap(text, cursor, room):
        """Visual rows of the input: each line is cut every `room` characters. Returns (rows, cursor row, cursor column)."""
        rows, cursor_row, cursor_column, offset = [], 0, 0, 0
        for line in text.split("\n"):
            pieces = [line[start:start + room] for start in range(0, len(line), room)] or [""]
            if offset <= cursor <= offset + len(line):
                column = cursor - offset
                if column == len(line) and line and len(line) % room == 0:
                    pieces.append("")              # the cursor after a full row starts the next one
                cursor_row, cursor_column = len(rows) + column // room, column % room
            rows.extend(pieces)
            offset += len(line) + 1
        return rows, cursor_row, cursor_column

    def layout(self, text, cursor):
        """The reserved rows as (row number, content) and the cursor's (row, column): pure, for drawing and tests."""
        width = max(self.columns, 4)
        room = max(1, width - 4)
        shade = bar(self.stream)
        pointer = paint("\u203a", "accent", "bold", stream=self.stream)
        hint = self.rows                           # from the bottom: hint, status, band (padding, text rows, padding)
        first_text = hint - 2 - self.lines
        top_pad = first_text - 1
        spacer = top_pad - self.listed - 1         # above the `/` list when it is open, so the list touches the band
        empty = shade + "\x1b[K\x1b[0m"
        if text:
            visual, cursor_row, column = self.wrap(text, cursor, room)
            start = min(max(0, cursor_row - self.lines + 1), max(0, len(visual) - self.lines))
            shown = visual[start:start + self.lines]
            cursor_row -= start
        else:
            shown, cursor_row, column = [None], 0, 0
        rows = [(spacer, "\x1b[2K"), (top_pad, empty)]
        for index in range(self.lines):
            head = shade + (pointer if index == 0 else " ") + shade + " "
            if index < len(shown) and shown[index] is not None:
                body = shown[index]
            elif index == 0 and not text:
                body = paint(PLACEHOLDER[:room], "muted", stream=self.stream) + shade
            else:
                body = ""
            rows.append((first_text + index, head + body + "\x1b[K\x1b[0m"))
        rows += [(hint - 2, empty),
                 (hint - 1, "\x1b[2K" + paint(self.status[:width - 1], "muted", stream=self.stream)),
                 (hint, "\x1b[2K" + paint((self.note or HINT)[:width - 1], "muted", stream=self.stream))]
        if self.listed:
            first = max(0, min(self.pick - self.listed + 1, len(self.commands) - self.listed))
            for offset, index in enumerate(range(first, first + self.listed)):
                rows.insert(1 + offset, (spacer + 1 + offset, self._command_row(index, width)))
        return rows, (first_text + cursor_row, 3 + column)

    def _command_row(self, index, width):
        if index >= len(self.commands):
            return "\x1b[2K"
        name, description = self.commands[index]
        if index == self.pick:
            if not enabled(self.stream):
                return "\x1b[2K" + ("\u203a %-14s %s" % (name, description))[:width - 1]
            rgb, basic = _PICKED
            colour = ("\x1b[48;2;%d;%d;%dm\x1b[38;2;20;22;30m" % rgb if bar(self.stream).startswith("\x1b[48;2")
                      else "\x1b[%sm\x1b[30m" % basic)
            return "\x1b[2K" + colour + ("\u203a %-14s %s" % (name, description))[:width - 1] + "\x1b[K\x1b[0m"
        return "\x1b[2K  " + ("%-14s " % name)[:width - 3] + paint(description[:max(0, width - 18)], "muted", stream=self.stream)

    def show_commands(self, commands, pick):
        """The `/` commands matching what is typed, listed above the band like Codex and Claude Code."""
        self.commands, self.pick = tuple(commands), pick

    def draw(self, text, cursor, typing=True):
        """Draw the input band with this text and leave the terminal cursor in it."""
        self.editing = (text, cursor)
        self._refresh_size(typing)
        visual = self.wrap(text, cursor, max(1, max(self.columns, 4) - 4))[0] if text else [""]
        self._reserve(len(self.commands), len(visual))
        rows, (row, column) = self.layout(text, cursor)
        self.cursor_at = (row, column)
        self.stream.write("".join("\x1b[%d;1H%s" % (number, content) for number, content in rows)
                          + "\x1b[%d;%dH" % (row, column))
        self.stream.flush()

    def submitted(self, text):
        """Back to the conversation: the sent message goes into the thread on the same band, the input is emptied."""
        self.note = ""
        self.commands = ()
        self._reserve(0, 1)
        shade = bar(self.stream)
        lines = [shade + "\x1b[K\x1b[0m"]
        for index, line in enumerate(text.split("\n")):
            head = paint("›", "accent", "bold", stream=self.stream) + shade + " " if index == 0 else "  "
            lines.append(shade + head + line + "\x1b[K\x1b[0m")
        lines.append(shade + "\x1b[K\x1b[0m")
        self.stream.write(self._back() + "\r\n".join(lines) + "\r\n\x1b7")
        self.draw("", 0, typing=False)
        self.editing = None
        self.stream.write(self._back())
        self.stream.flush()

    def enter(self):
        """Remember where the conversation text stops, before the cursor moves into the input band."""
        self.stream.write("\x1b7")

    def leave(self):
        """Return the cursor to the conversation without echoing anything (a cancelled or local input)."""
        self.note = ""
        self.commands = ()
        self._reserve(0, 1)
        self.draw("", 0, typing=False)
        self.editing = None
        self.stream.write(self._back())
        self.stream.flush()

    # -- full-screen view ---------------------------------------------------------------------------------------------
    def begin(self):
        """Draw the head of the conversation into the full-screen view (it starts empty); a no-op otherwise."""
        if self.screen is None or self.repaint is None:
            return
        try:
            self.stream.write(self._back())
            self.repaint()
        except (OSError, ValueError, TypeError, KeyError):
            pass
        self.stream.write("\x1b7")
        self._mark = self.screen.model.total(self._top())
        self.stream.flush()

    def mouse(self, on):
        """Wheel reports while a reader of this program parses them; off for anyone else (sudo, a plain prompt)."""
        if self.screen is None or bool(on) == self._mouse:
            return
        if not on and self.screen.selecting:
            self._selection = None
            self.screen.unfreeze(self._top(), columns=self.columns)
        self._mouse = bool(on)
        self.screen.raw(_MOUSE_ON if on else _MOUSE_OFF)

    @property
    def viewing(self):
        return self.screen is not None and self.screen.offset > 0

    def mouse_event(self, key):
        """A click or drag in the conversation: select text with the left button; releasing copies it. A double
        click selects a word. Other buttons and the input rows are ignored."""
        if self.screen is None:
            return
        match = _REPORT.fullmatch(key.decode("ascii", "replace") if type(key) is bytes else key)
        if not match:
            return
        button, column, row, kind = int(match.group(1)), int(match.group(2)) - 1, int(match.group(3)) - 1, match.group(4)
        top = self._top()
        raw_row = row
        row = min(max(row, 0), top - 1)
        start, _ = self.screen.model.window(top, self.screen.offset)
        point = (start + row, max(0, min(column, self.columns - 1)))
        state = getattr(self, "_selection", None)
        if kind == "M" and button & ~(4 | 8 | 16) == 0:                 # left press
            if row > top - 1 or int(match.group(3)) - 1 >= top:
                return                                                  # on the input rows: not a selection
            now = time.monotonic()
            double = (state is not None and state.get("released") and now - state["at"] < DOUBLE_CLICK
                      and state["anchor"] == point)
            if double:
                first, last = self.screen.model.word_at(top, *point)
                self._selection = {"anchor": (point[0], first), "point": (point[0], last), "at": now,
                                   "released": False, "moved": True}
            else:
                self._selection = {"anchor": point, "point": point, "at": now, "released": False, "moved": False}
            self.screen.selecting = True
            self.screen.highlight(top, self._selection["anchor"], self._selection["point"])
        elif kind == "M" and button & ~(4 | 8 | 16) == 32 and state is not None and not state["released"]:
            state["point"], state["moved"] = point, True                # a drag with the left button held
            state["column"] = point[1]
            # At the top row, or below the conversation (over the input): the view scrolls while the button is held
            # there, as in a terminal, and the selection follows.
            state["edge"] = 1 if raw_row <= 0 else -1 if raw_row >= top else 0
            self.screen.highlight(top, state["anchor"], point)
            if state["edge"] and not state.get("scrolling"):
                state["scrolling"] = True
                threading.Thread(target=self._edge_scroll, args=(state,), name="ai-desktop-select-scroll",
                                 daemon=True).start()
        elif kind == "m" and state is not None and not state["released"]:
            state["released"], state["at"], state["edge"] = True, time.monotonic(), 0
            if not state["moved"]:
                self.screen.unfreeze(top, columns=self.columns)         # a single click: nothing selected
                return
            text = self.screen.model.text_between(top, state["anchor"], state["point"])
            copied = text.strip() and copy_to_clipboard(text, self._plain)
            self.screen.unfreeze(top, "copied %d characters to the clipboard" % len(text) if copied else None,
                                 columns=self.columns)

    EDGE_STEP = 0.06                                                    # seconds between rows while held at an edge

    def _edge_scroll(self, state):
        """Scroll one row at a time while a drag is held at the top edge or over the input; the selection grows."""
        try:
            while True:
                time.sleep(self.EDGE_STEP)
                with self.screen.lock:
                    if getattr(self, "_selection", None) is not state or state["released"] or not state["edge"]:
                        return
                    top = self._top()
                    offset = max(0, min(self.screen.offset + state["edge"], len(self.screen.model.history)))
                    if offset == self.screen.offset:
                        continue                                        # at the start or the end: wait for a move
                    self.screen.show(offset, top, self.columns)
                    start, _ = self.screen.model.window(top, offset)
                    state["point"] = (start + (0 if state["edge"] > 0 else top - 1), state["column"])
                    self.screen.highlight(top, state["anchor"], state["point"])
        finally:
            state["scrolling"] = False

    def scroll(self, key):
        """Move the full-screen view: a page, three rows for the wheel, or back to the live conversation."""
        if self.screen is None:
            return
        state = getattr(self, "_selection", None)
        if self.screen.selecting and key in (b"wheel-up", b"wheel-down", b"page-up", b"page-down") and state:
            # The wheel during a drag scrolls and keeps the selection, like a terminal.
            step = {b"wheel-up": 3, b"wheel-down": -3}.get(key, max(1, self._top() - 1) * (1 if key == b"page-up" else -1))
            with self.screen.lock:
                self.screen.show(self.screen.offset + step, self._top(), self.columns)
                self.screen.highlight(self._top(), state["anchor"], state["point"])
            return
        if self.screen.selecting:
            self._selection = None
            self.screen.unfreeze(self._top(), columns=self.columns)      # a key ends an unfinished selection
        page = max(1, self._top() - 1)
        step = {b"page-up": page, b"page-down": -page, b"wheel-up": 3, b"wheel-down": -3}.get(key)
        offset = 0 if step is None else self.screen.offset + step
        self.screen.show(offset, self._top(), self.columns)

    def stop(self):
        try:
            if self._previous_handler is not None:
                signal.signal(signal.SIGWINCH, self._previous_handler)
        except (ValueError, OSError):
            pass
        if self.screen is not None:
            self.scroll(b"scroll-end")
            self.mouse(False)
            lines = self.screen.model.transcript(self._top(), since=self._mark)
            self.screen.raw("\x1b[r" + _LEAVE_FULL)
            if sys.stdout is self.screen:
                sys.stdout = self._plain
            # The conversation stays in the terminal's own history after the full-screen view closes.
            self._plain.write("".join(line + "\x1b[0m\n" for line in lines))
            self._plain.flush()
            return
        self.stream.write("\x1b[r\x1b[%d;1H\x1b[J" % (self._top() + 1))
        self.stream.flush()


def usable(stream):
    """A colour terminal with room for the pinned input."""
    try:
        if not (enabled(stream) and stream.isatty() and os.isatty(stream.fileno())):
            return False
    except (OSError, ValueError, AttributeError):
        return False
    rows, columns = _size(stream)
    return rows >= MIN_ROWS and columns >= 20


def clear_view(stream):
    """Start the conversation at the top of the window, like Codex: what was on the screen is scrolled up into the
    terminal's own history (not erased), then the cursor goes to the first row."""
    if not usable(stream):
        return
    rows, _ = _size(stream)
    stream.write("\x1b[%d;1H" % rows + "\n" * rows + "\x1b[H")
    stream.flush()


def start(stream, status, *, fullscreen=None):
    """Pin the input to the bottom when the terminal can show it; return the frame or None. The full-screen view is
    the default (`fullscreen=None` reads the owner's setting)."""
    global _current
    if _current is not None:
        return _current
    if not usable(stream):
        return None
    if fullscreen is None:
        fullscreen = view_setting() == "fullscreen"
    _current = Frame(stream, status, fullscreen=bool(fullscreen))
    _current.start()
    return _current


def stop():
    global _current
    frame, _current = _current, None
    if frame is not None:
        try:
            frame.stop()
        except (OSError, ValueError):
            pass
