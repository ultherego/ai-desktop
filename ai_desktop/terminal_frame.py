"""The input area pinned to the bottom of the terminal window during an interactive conversation.

The terminal's scroll region keeps everything the program prints (answers, command rows, consent questions) above a
fixed block of RESERVED rows: a three-row input band, a status line and a key hint. Every byte written here is
generated by this module; the user's text reaches it already validated by the editor. Colour terminals only; anything
else keeps the ordinary inline prompt.
"""
import os
import signal

from .terminal_style import bar, enabled, paint

RESERVED = 5               # band top padding, input row, band bottom padding, status, hint
MIN_ROWS = 12
PLACEHOLDER = "Ask ai-desktop to do anything"
HINT = "enter send · \\ enter new line · / commands · ctrl+c clear"

_current = None


def current():
    """The active frame, or None (then the editor draws inline as before)."""
    return _current


def _size(stream):
    try:
        size = os.get_terminal_size(stream.fileno())
        return size.lines, size.columns
    except (OSError, ValueError, AttributeError):
        return 0, 0


class Frame:
    def __init__(self, stream, status):
        self.stream = stream
        self.status = status
        self.rows, self.columns = _size(stream)
        self.note = ""
        self._resized = False
        self._moved = False                        # the window changed size since the conversation position was saved
        self.editing = None                        # (text, cursor) while the editor waits for keys
        self._previous_handler = None

    # -- region ------------------------------------------------------------------------------------------------------
    def _region(self):
        """Keep the cursor above the reserved rows and limit scrolling to the area above them."""
        top = self.rows - RESERVED
        # Make room first: newlines scroll old content up when the cursor is low, then the cursor goes back up.
        self.stream.write("\n" * RESERVED + "\x1b[%dA" % RESERVED + "\x1b7" + "\x1b[1;%dr" % top + "\x1b8")

    def start(self):
        self._region()
        try:
            self._previous_handler = signal.signal(signal.SIGWINCH, self._on_resize)
        except (ValueError, OSError):              # not the main thread: resizing is then handled on the next draw
            self._previous_handler = None
        self.draw("", 0)
        self.editing = None
        self.stream.write("\x1b8")                 # back to the conversation, above the reserved rows
        self.stream.flush()

    def _on_resize(self, *unused):
        """Redraw at once while the editor waits for a key, so the band follows the window; otherwise on the next draw."""
        self._resized = True
        if self.editing is not None:
            try:
                self.draw(*self.editing)
            except (OSError, ValueError):
                pass

    def _refresh_size(self):
        rows, columns = _size(self.stream)
        if (rows, columns) != (self.rows, self.columns) or self._resized:
            self._resized = False
            old = self.rows - RESERVED
            self.rows, self.columns = rows, columns
            # The old reserved rows may now sit inside the conversation: clear from whichever reserved block starts
            # higher, then set the region again. No save/restore here: that slot holds the conversation position.
            top = self.rows - RESERVED
            self.stream.write("\x1b[r\x1b[%d;1H\x1b[J\x1b[1;%dr" % (max(1, min(old, top) + 1), top))
            self._moved = True

    def _back(self):
        """To the conversation text: the saved position, or the last region row when the window size changed."""
        if self._moved:
            self._moved = False
            return "\x1b[%d;1H" % (self.rows - RESERVED)
        return "\x1b8"

    # -- drawing -----------------------------------------------------------------------------------------------------
    def layout(self, text, cursor):
        """The reserved rows as (row number, content) and the cursor's (row, column): pure, for drawing and tests."""
        top = self.rows - RESERVED + 1
        width = max(self.columns, 4)
        shade = bar(self.stream)
        pointer = paint("›", "accent", "bold", stream=self.stream)
        if text:
            room = width - 4
            start = max(0, cursor - room + 1)
            shown, column = text[start:start + room], cursor - start
            body = shade + "  " + shade + shown
        else:
            body = shade + "  " + paint(PLACEHOLDER[:width - 4], "muted", stream=self.stream) + shade
            column = 0
        empty = shade + "\x1b[K\x1b[0m"
        rows = [(top, empty),
                (top + 1, shade + pointer + shade + body[len(shade) + 1:] + "\x1b[K\x1b[0m"),
                (top + 2, empty),
                (top + 3, "\x1b[2K" + paint(self.status[:width - 1], "muted", stream=self.stream)),
                (top + 4, "\x1b[2K" + paint((self.note or HINT)[:width - 1], "muted", stream=self.stream))]
        return rows, (top + 1, 3 + column)

    def draw(self, text, cursor):
        """Draw the input band with this text and leave the terminal cursor in it."""
        self.editing = (text, cursor)
        self._refresh_size()
        rows, (row, column) = self.layout(text, cursor)
        self.stream.write("".join("\x1b[%d;1H%s" % (number, content) for number, content in rows)
                          + "\x1b[%d;%dH" % (row, column))
        self.stream.flush()

    def submitted(self, text):
        """Back to the conversation: the sent message goes into the thread on the same band, the input is emptied."""
        self.note = ""
        shade = bar(self.stream)
        lines = [shade + "\x1b[K\x1b[0m"]
        for index, line in enumerate(text.split("\n")):
            head = paint("›", "accent", "bold", stream=self.stream) + shade + " " if index == 0 else "  "
            lines.append(shade + head + line + "\x1b[K\x1b[0m")
        lines.append(shade + "\x1b[K\x1b[0m")
        self.stream.write(self._back() + "\r\n".join(lines) + "\r\n\x1b7")
        self.draw("", 0)
        self.editing = None
        self.stream.write(self._back())
        self.stream.flush()

    def enter(self):
        """Remember where the conversation text stops, before the cursor moves into the input band."""
        self.stream.write("\x1b7")

    def leave(self):
        """Return the cursor to the conversation without echoing anything (a cancelled or local input)."""
        self.note = ""
        self.draw("", 0)
        self.editing = None
        self.stream.write(self._back())
        self.stream.flush()

    def stop(self):
        try:
            if self._previous_handler is not None:
                signal.signal(signal.SIGWINCH, self._previous_handler)
        except (ValueError, OSError):
            pass
        top = self.rows - RESERVED
        self.stream.write("\x1b[r\x1b[%d;1H\x1b[J" % (top + 1))
        self.stream.flush()


def usable(stream):
    """A colour terminal with room for the pinned input."""
    try:
        if not (enabled(stream) and stream.isatty() and os.isatty(stream.fileno())):
            return False
    except (OSError, ValueError, AttributeError):
        return False
    rows, columns = _size(stream)
    return rows >= MIN_ROWS and columns >= 20


def clear_view(stream):
    """Start the conversation at the top of the window, like Codex: what was on the screen is scrolled up into the
    terminal's own history (not erased), then the cursor goes to the first row."""
    if not usable(stream):
        return
    rows, _ = _size(stream)
    stream.write("\x1b[%d;1H" % rows + "\n" * rows + "\x1b[H")
    stream.flush()


def start(stream, status):
    """Pin the input to the bottom when the terminal can show it; return the frame or None."""
    global _current
    if _current is not None:
        return _current
    if not usable(stream):
        return None
    _current = Frame(stream, status)
    _current.start()
    return _current


def stop():
    global _current
    frame, _current = _current, None
    if frame is not None:
        try:
            frame.stop()
        except (OSError, ValueError):
            pass
